"""Pack approved bookends for ltx25-docker.

Output, under `output/ltx_ready/`:

  shot_001_ltx.tar.gz   start.jpg, stop.jpg, prompt.txt, audio.wav, sidecars
  manifest.json         one entry per shot, with seeds and sizes
and `output/ltx_ready_batch.tar.gz` -- one file to scp to the render box.

The heavy Tripo references are deliberately dropped: they were the input, not the
deliverable, and they are what makes these archives too big to move.

FLF2V CLI flags are NOT invented here. `--start-args` / `--stop-args` are filled
in by the operator after running `--help` on the LTX pipeline (see
docs/HANDOFF.md); without them the pack still happens, but no render script is
written, because a script with guessed flags is worse than no script.
"""
from __future__ import annotations

import json
import tarfile
from pathlib import Path

from .config import Config
from .shot import Shot

CARRY = ("prompt.txt", "audio.wav", "start.json", "stop.json")


def pack(
    cfg: Config,
    shots: list[Shot],
    *,
    out_dir: Path | None = None,
    allow_incomplete: bool = False,
    start_args: str | None = None,
    stop_args: str | None = None,
    emit_render_sh: bool = False,
) -> dict:
    out_dir = Path(out_dir) if out_dir else Path(cfg.output_dir)
    ready = out_dir / "ltx_ready"
    ready.mkdir(parents=True, exist_ok=True)

    entries: list[dict] = []
    skipped: list[dict] = []
    for shot in shots:
        start, stop, prompt = shot.root / "start.jpg", shot.root / "stop.jpg", shot.root / "prompt.txt"
        missing = [p.name for p in (start, stop, prompt) if not p.is_file()]
        if missing:
            entry = {"shot": shot.name, "missing": missing}
            if allow_incomplete:
                entry["note"] = "packed anyway (--allow-incomplete)"
            else:
                skipped.append(entry)
                continue

        archive = ready / f"{shot.name}_ltx.tar.gz"
        members = [p for p in (start, stop, prompt) if p.is_file()]
        members += [shot.root / name for name in CARRY if (shot.root / name).is_file()]
        with tarfile.open(archive, "w:gz") as tar:
            for member in members:
                tar.add(member, arcname=member.name)

        entry = {
            "shot": shot.name,
            "archive": archive.name,
            "files": [m.name for m in members],
            "has_audio": (shot.root / "audio.wav").is_file(),
            "size": [cfg.width, cfg.height],
            "seeds": _seeds(shot.root),
        }
        entries.append(entry)

    if not entries:
        return {"ready_dir": str(ready), "packed": 0, "skipped": skipped, "note": "nothing complete to pack"}

    manifest = {
        "schema": 1,
        "model": {"id": cfg.model_id, "revision": cfg.revision},
        "style": cfg.style,
        "size": [cfg.width, cfg.height],
        "shots": entries,
    }
    (ready / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")

    bundle = out_dir / "ltx_ready_batch.tar.gz"
    with tarfile.open(bundle, "w:gz") as tar:
        tar.add(ready, arcname="ltx_ready")

    result = {
        "ready_dir": str(ready),
        "bundle": str(bundle),
        "packed": len(entries),
        "skipped": skipped,
        "shots": [e["shot"] for e in entries],
    }

    if emit_render_sh:
        if start_args and stop_args:
            script = _render_script(entries, start_args, stop_args)
            (ready / "render.sh").write_text(script, encoding="utf-8")
            (ready / "render.sh").chmod(0o755)
            result["render_sh"] = str(ready / "render.sh")
        else:
            (ready / "render_plan.txt").write_text(_render_plan(entries), encoding="utf-8")
            result["render_plan"] = str(ready / "render_plan.txt")
            result["warning"] = (
                "no --start-args/--stop-args supplied, so render.sh was not written. Verify the "
                "FLF2V flags first (docs/HANDOFF.md) and re-run pack with them."
            )
    return result


def _seeds(root: Path) -> dict:
    seeds = {}
    for tag in ("start", "stop"):
        sidecar = root / f"{tag}.json"
        if sidecar.is_file():
            try:
                seeds[tag] = json.loads(sidecar.read_text(encoding="utf-8")).get("seed")
            except (OSError, json.JSONDecodeError):
                seeds[tag] = None
    return seeds


def _render_script(entries: list[dict], start_args: str, stop_args: str) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by `bookends pack`.",
        "# FLF2V flags were supplied at pack time, so they are the verbatim flags this",
        "# project verified against: python -m ltx_pipelines.distilled --help",
        "set -euo pipefail",
        'HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"',
        "render() {",
        '  local d="$1"',
        "  ltx2-run --prompt-file \"$d/prompt.txt\" \\",
        f"    {start_args} \"$d/start.jpg\" \\",
        f"    {stop_args} \"$d/stop.jpg\"",
        "}",
        "",
    ]
    for entry in entries:
        lines.append(f"# {entry['shot']}")
        lines.append(f'render "$HERE/extracted/{entry["shot"]}"')
    return "\n".join(lines) + "\n"


def _render_plan(entries: list[dict]) -> str:
    lines = [
        "Command skeletons, NOT runnable until the FLF2V flags are verified.",
        "",
        "To verify, on the ltx25-docker box:",
        "  docker compose run --rm ltx2 python -m ltx_pipelines.distilled --help",
        "",
        "Then re-run: bookends pack --emit-render-sh \\",
        "  --start-args '<verified args for frame 0>' \\",
        "  --stop-args  '<verified args for the last frame>'",
        "",
        "For reference, scripts/paint_still.py in ltx25-docker uses the form",
        "  --image PATH FRAME STRENGTH guide|replace",
        "with FRAME=0 for a start frame; the last-frame index convention is unconfirmed.",
        "",
    ]
    for entry in entries:
        lines.append(f"# {entry['shot']}")
        lines.append(f'ltx2-run --prompt-file extracted/{entry["shot"]}/prompt.txt \\')
        lines.append(f'  <start args> extracted/{entry["shot"]}/start.jpg \\')
        lines.append(f'  <stop args>  extracted/{entry["shot"]}/stop.jpg')
        lines.append("")
    return "\n".join(lines)
